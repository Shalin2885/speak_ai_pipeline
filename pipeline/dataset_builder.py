"""
pipeline/dataset_builder.py
Assembles a Whisper-ready dataset manifest (JSONL) from:
  - Real audio transcribed by transcription.py
  - Synthetic audio generated by speech_synthesis.py
  - Augmented audio produced by augmentation.py

The manifest format is compatible with Repository 1's prepare_for_whisper.py:
  {"audio_filepath": "...", "text": "...", "duration": <seconds>}

Optionally splits the manifest into train / validation / test sets.
"""

from __future__ import annotations

import json
import logging
import random
from pathlib import Path
from typing import Optional

import soundfile as sf

logger = logging.getLogger(__name__)


def _audio_duration(audio_path: Path) -> Optional[float]:
    """Return the duration in seconds of an audio file, or None on failure."""
    try:
        info = sf.info(str(audio_path))
        return info.duration
    except Exception:
        return None


def _build_entry(audio_path: Path, text: str) -> Optional[dict]:
    """Create a single manifest entry, or None if the audio is unreadable."""
    duration = _audio_duration(audio_path)
    if duration is None:
        logger.warning("Cannot read audio (skipped): %s", audio_path)
        return None
    return {
        "audio_filepath": str(audio_path.resolve()),
        "text": text.strip(),
        "duration": round(duration, 3),
    }


# ── Manifest assembly ─────────────────────────────────────────────────────────

def build_manifest(
    transcripts_dir: Path,
    manifests_dir: Path,
    output_name: str = "dataset",
    include_augmented: Optional[Path] = None,
    include_synthetic: Optional[Path] = None,
    synthetic_manifest: Optional[Path] = None,
) -> Path:
    """
    Build a JSONL manifest from validated transcript sidecars.

    Parameters
    ----------
    transcripts_dir:    Directory of JSON sidecar files produced by transcription.py.
    manifests_dir:      Destination directory for the output manifest.
    output_name:        Stem of the output JSONL file.
    include_augmented:  Optional directory of augmented WAVs to add (paired by stem).
    include_synthetic:  Optional directory of synthetic WAVs; requires *synthetic_manifest*.
    synthetic_manifest: JSONL manifest produced by TTS with a 'text' field per line.

    Returns path to the written manifest.
    """
    manifests_dir.mkdir(parents=True, exist_ok=True)
    entries: list[dict] = []

    # 1. Real (and optionally augmented) audio from transcript sidecars
    for jf in sorted(transcripts_dir.glob("*.json")):
        if jf.parent.name == "quarantine":
            continue
        try:
            data = json.loads(jf.read_text(encoding="utf-8"))
        except Exception as exc:
            logger.error("Cannot parse %s: %s", jf, exc)
            continue

        audio_path = Path(data.get("audio_filepath") or data.get("audio_path", ""))
        text = data.get("text", "").strip()
        if not text or not audio_path.exists():
            logger.warning("Missing audio or text for %s — skipping.", jf.name)
            continue

        entry = _build_entry(audio_path, text)
        if entry:
            entries.append(entry)

        # Augmented variant with the same text
        if include_augmented:
            aug_path = include_augmented / audio_path.name
            if aug_path.exists():
                aug_entry = _build_entry(aug_path, text)
                if aug_entry:
                    aug_entry["source"] = "augmented"
                    entries.append(aug_entry)

    # 2. Synthetic audio
    if include_synthetic and synthetic_manifest and synthetic_manifest.exists():
        synth_lines = [
            json.loads(l)
            for l in synthetic_manifest.read_text(encoding="utf-8").splitlines()
            if l.strip()
        ]
        synth_files = sorted(include_synthetic.glob("*.wav"))
        for synth_file, synth_data in zip(synth_files, synth_lines):
            text = synth_data.get("text", "").strip()
            if not text:
                continue
            entry = _build_entry(synth_file, text)
            if entry:
                entry["source"] = "synthetic"
                entries.append(entry)

    if not entries:
        logger.error("No valid entries — manifest not written.")
        raise ValueError("Dataset builder produced zero entries.")

    out_path = manifests_dir / f"{output_name}.jsonl"
    with out_path.open("w", encoding="utf-8") as fh:
        for e in entries:
            fh.write(json.dumps(e, ensure_ascii=False) + "\n")

    logger.info("Manifest written: %s (%d entries)", out_path, len(entries))
    return out_path


# ── Train / Val / Test split ──────────────────────────────────────────────────

def split_manifest(
    manifest_path: Path,
    manifests_dir: Path,
    train_ratio: float = 0.80,
    val_ratio: float = 0.10,
    seed: int = 42,
) -> dict[str, Path]:
    """
    Split a manifest into train / validation / test subsets.

    Returns dict: {'train': Path, 'val': Path, 'test': Path}.
    """
    manifests_dir.mkdir(parents=True, exist_ok=True)
    lines = manifest_path.read_text(encoding="utf-8").splitlines()
    rng = random.Random(seed)
    rng.shuffle(lines)

    n = len(lines)
    n_train = int(n * train_ratio)
    n_val = int(n * val_ratio)

    splits = {
        "train": lines[:n_train],
        "val": lines[n_train : n_train + n_val],
        "test": lines[n_train + n_val :],
    }

    paths: dict[str, Path] = {}
    for name, subset in splits.items():
        out = manifests_dir / f"{manifest_path.stem}_{name}.jsonl"
        out.write_text("\n".join(subset) + "\n", encoding="utf-8")
        logger.info("Split '%s': %d entries → %s", name, len(subset), out)
        paths[name] = out

    return paths

